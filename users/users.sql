--Create el Manager by el DBA (connection manager)
CREATE USER GYM_MANAGER IDENTIFIED BY Manager111;
CREATE ROLE MANAGER_ROLE;
GRANT CREATE SESSION,
      CREATE USER,
      ALTER USER,
      GRANT ANY PRIVILEGE
TO MANAGER_ROLE;

GRANT SELECT ON SYS.V_$SESSION TO MANAGER_ROLE;
GRANT MANAGER_ROLE TO GYM_MANAGER;


-- Create el Users by the Manager
CREATE USER GYM_DEVELOPER IDENTIFIED BY Developer111;
CREATE USER GYM_STAFF IDENTIFIED BY Staff111;


--Giving role access to developer by manager (connection developer)
GRANT CREATE SESSION TO GYM_DEVELOPER WITH ADMIN OPTION;
GRANT CREATE TABLE,
      CREATE SEQUENCE,
      CREATE VIEW,
      CREATE PROCEDURE,
      CREATE TRIGGER
TO GYM_DEVELOPER;
ALTER USER GYM_DEVELOPER QUOTA UNLIMITED ON USERS;


--Giving role access to staff by developer
GRANT CREATE SESSION TO GYM_STAFF;

--closing user account and then opening
ALTER USER GYM_STAFF ACCOUNT LOCK;
ALTER USER GYM_STAFF ACCOUNT UNLOCK;

--Displaying session info
SELECT USERNAME, SID, SERIAL#
FROM V$SESSION
WHERE SID = SYS_CONTEXT('USERENV', 'SID');

--Displaying Manager name and role
SELECT GRANTEE, GRANTED_ROLE
FROM DBA_ROLE_PRIVS
WHERE GRANTEE = 'GYM_MANAGER';

--Displaying specified roles for each User
SELECT GRANTEE, PRIVILEGE, ADMIN_OPTION
FROM DBA_SYS_PRIVS
WHERE GRANTEE IN (
    'MANAGER_ROLE',
    'GYM_DEVELOPER',
    'GYM_STAFF'
);
